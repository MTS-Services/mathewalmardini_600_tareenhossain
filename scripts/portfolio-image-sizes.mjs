// Regenerates src/data/portfolioImageSizes.js with the pixel size of every
// portfolio image, so the gallery can reserve space and balance its columns
// before images load. Run after adding images: node scripts/portfolio-image-sizes.mjs
import { writeFile } from "node:fs/promises";
import sharp from "sharp";
import { portfolioData } from "../src/data/portfolioData.js";

const OUTPUT = new URL("../src/data/portfolioImageSizes.js", import.meta.url);

const readSize = async (src) => {
  const response = await fetch(src);
  if (!response.ok) throw new Error(`${response.status} ${src}`);
  const { width, height } = await sharp(
    Buffer.from(await response.arrayBuffer()),
  ).metadata();
  return [width, height];
};

const sizes = {};
const srcs = [...new Set(portfolioData.map((image) => image.src))];

for (let i = 0; i < srcs.length; i += 8) {
  const batch = srcs.slice(i, i + 8);
  const results = await Promise.allSettled(batch.map(readSize));
  results.forEach((result, j) => {
    if (result.status === "fulfilled") {
      sizes[batch[j]] = result.value;
    } else {
      console.warn(`Skipped: ${result.reason.message}`);
    }
  });
}

const body = Object.entries(sizes)
  .map(([src, [w, h]]) => `  ${JSON.stringify(src)}: [${w}, ${h}],`)
  .join("\n");

await writeFile(
  OUTPUT,
  `// Generated by scripts/portfolio-image-sizes.mjs — [width, height] per image\nexport const portfolioImageSizes = {\n${body}\n};\n`,
);

console.log(`Wrote ${Object.keys(sizes).length}/${srcs.length} image sizes`);
